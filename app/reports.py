class BadFile(ValueError):
    pass


def _num(s):
    s = str(s or "").replace(",", "").replace("Rs", "").replace("₹", "").strip()
    if not s:
        return None
    try:
        return float(s)
    except ValueError:
        raise BadFile(f"'{s[:20]}' is not an amount.")


def _norm_status(s):
    s = (s or "").strip().lower()
    return "active" if s in ("active", "live", "open", "running", "") else s


def parse(name: str, data: bytes):
    """Returns ("register", [rows]) or ("statement", [entries])."""
    if len(data) > MAX_BYTES:
        raise BadFile("File is larger than 2 MB.")
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise BadFile("File is not UTF-8 text.")
    head = text.lstrip()[:400]
    if head.startswith("<"):
        return "statement", _camt(text)
    if ":20:" in head or ":61:" in text[:4000]:
        return "statement", _mt940(text)
    return "register", _csv(text)


def _csv(text):
    rd = csv.DictReader(io.StringIO(text))
    if not rd.fieldnames:
        raise BadFile("Empty CSV.")
    cols = {c.strip().lower().replace(" ", "_"): c for c in rd.fieldnames}
    if "fd_number" not in cols:
        raise BadFile("CSV needs an fd_number column.")
    out = []
    for i, row in enumerate(rd, 2):
        g = lambda k: (row.get(cols[k]) or "").strip() if k in cols else ""
        if not g("fd_number"):
            continue
        out.append({"line": i, "fd_number": g("fd_number").upper(), "principal": _num(g("principal")),
                    "maturity": g("maturity"), "status": _norm_status(g("status")), "lien": g("lien")})
        if len(out) > 20000:
            raise BadFile("More than 20,000 rows.")
    return out


def _camt(text):
    if "<!DOCTYPE" in text or "<!ENTITY" in text:
        raise BadFile("DTDs/entities are not allowed in statements.")
    try:
        root = ET.fromstring(text)
    except ET.ParseError:
        raise BadFile("Not well-formed XML.")
    if "camt.053" not in (root.tag + text[:600]):
        raise BadFile("XML is not an ISO 20022 camt.053 statement.")
    out = []
    for el in root.iter():
        if el.tag.endswith("}Ntry") or el.tag == "Ntry":
            txt, amt, cd, dt = [], None, "", ""
            for c in el.iter():
                t = c.tag.split("}")[-1]
                if t == "Amt":
                    amt = _num(c.text)
                elif t == "CdtDbtInd":
                    cd = (c.text or "").strip()
                elif t in ("Dt", "DtTm") and not dt:
                    dt = (c.text or "")[:10]
                elif c.text and t in ("AcctSvcrRef", "Ustrd", "AddtlNtryInf", "AddtlTxInf", "EndToEndId", "Ref", "Nm"):
                    txt.append(c.text.strip())
            out.append({"date": dt, "amount": amt, "dir": "credit" if cd == "CRDT" else "debit", "text": " ".join(txt)})
    return out


def _mt940(text):
    out, cur = [], None
    for line in text.splitlines():
        if line.startswith(":61:"):
            m = re.match(r":61:(\d{6})(\d{4})?(R?[CD])([A-Z])?([\d,]+)", line)
            if not m:
                raise BadFile("Unreadable :61: line in MT940.")
            d = m.group(1)
            cur = {"date": f"20{d[:2]}-{d[2:4]}-{d[4:]}", "amount": _num(m.group(5).replace(",", ".")),
                   "dir": "credit" if m.group(3).endswith("C") else "debit", "text": line[4:]}
            out.append(cur)
        elif line.startswith(":86:") and cur is not None:
            cur["text"] += " " + line[4:]
        elif cur is not None and not line.startswith(":") and line.strip() not in ("", "-"):
            cur["text"] += " " + line.strip()
        elif line.startswith(":"):
            cur = None if not line.startswith(":86:") else cur
    return out


def reconcile(kind, items, rows):
    """Compare a bank file against the register. Returns a list of findings (dict: level, fdr, text)."""
    reg = {r["f"]["fd_number"].upper(): r for r in rows}
    live = {k: r for k, r in reg.items() if r["status"][0] not in ("released", "renewed")}
    find = []
    if kind == "register":
        seen = set()
        for it in items:
            fd = it["fd_number"]
            seen.add(fd)
            r = reg.get(fd)
            if not r:
                find.append({"level": "info", "fdr": None, "fd": fd, "text": f"Bank file line {it['line']}: FD not on the AICTE register (pledged to AICTE but never filed?)."})
                continue
            if r["status"][0] in ("released", "renewed"):
                continue
            f = r["f"]
            if it["principal"] is not None and abs(it["principal"] - float(f["principal"])) > 0.5:
                find.append({"level": "bad", "fdr": f["id"], "fd": fd, "text": f"Principal differs: register Rs {float(f['principal']):,.2f}, bank file Rs {it['principal']:,.2f}."})
            if it["maturity"] and it["maturity"] != f["maturity"]:
                find.append({"level": "bad", "fdr": f["id"], "fd": fd, "text": f"Maturity differs: register {f['maturity']}, bank file {it['maturity']}."})
            if it["status"] != "active":
                find.append({"level": "bad", "fdr": f["id"], "fd": fd, "text": f"Bank file shows status '{it['status']}'."})
            if it["lien"] and "aicte" not in it["lien"].lower():
                find.append({"level": "bad", "fdr": f["id"], "fd": fd, "text": f"Lien not in favour of AICTE: '{it['lien'][:60]}'."})
        for fd, r in live.items():
            if fd not in seen and r["f"]["bank_host"]:
                find.append({"level": "warn", "fdr": r["f"]["id"], "fd": fd, "text": "Registered FD is missing from the bank's file."})
    else:
        for e in items:
            hit = [fd for fd in live if fd in (e["text"] or "").upper()]
            for fd in hit:
                r = live[fd]
                amt = f"Rs {e['amount']:,.2f}" if e["amount"] is not None else "an amount"
                find.append({"level": "warn", "fdr": r["f"]["id"], "fd": fd,
                             "text": f"Statement {e['dir']} of {amt} on {e['date'] or 'unknown date'} references this FD (possible encashment, loan or interest payout)."})
    order = {"bad": 0, "warn": 1, "info": 2}
    return sorted(find, key=lambda x: order[x["level"]])
