"""Reports, maturity calendar and bank-file reconciliation.

Reconciliation is a CROSS-CHECK, never a verdict: a statement or FD register file from a bank is not
signed by the bank's server the way a session proof is, so a mismatch only puts the deposit on the
"re-check" list and offers a one-click fresh bank proof. Nothing is accepted or rejected from a file.

Accepted bank files (all common Indian/ISO bank exports):
  * CSV FD register      columns: fd_number, principal, maturity, status, lien  (header names case-insensitive)
  * ISO 20022 CAMT.053   account statement; entries whose reference/remittance text names a registered FD
  * SWIFT MT940          account statement; :61:/:86: pairs whose text names a registered FD
"""
import csv
import io
import re
import xml.etree.ElementTree as ET
from datetime import date

MAX_BYTES = 2 * 1024 * 1024
_FORMULA = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(v):
    """Neutralise spreadsheet formula injection (CSV/XLSX opened in Excel)."""
    s = "" if v is None else str(v)
    return "'" + s if s.startswith(_FORMULA) else s


def kpis(rows):
    live = [r for r in rows if r["status"][0] not in ("released", "renewed")]
    by = {}
    for r in rows:
        by[r["status"][0]] = by.get(r["status"][0], 0) + 1
    principal = sum(float(r["f"]["principal"]) for r in live)
    conf = [r for r in live if r["status"][0] in ("confirmed", "release_pending")]
    today = date.today()
    m90 = sum(1 for r in live if 0 <= (date.fromisoformat(r["f"]["maturity"]) - today).days <= 90)
    return {"total": len(rows), "live": len(live), "principal": principal,
            "confirmed": len(conf), "confirmed_pct": round(100 * len(conf) / len(live)) if live else 0,
            "confirmed_principal": sum(float(r["f"]["principal"]) for r in conf),
            "flagged": sum(by.get(k, 0) for k in ("discrepancy", "escalated", "on_hold")),
            "maturing_90": m90, "by_status": by}


HEAD = ["FDR ID", "Institution ID", "Institution", "FD number", "Bank", "Principal (Rs)", "Issue date", "Maturity", "Status", "Status detail", "Last bank check (decision)"]


def register_rows(rows):
    out = []
    for r in rows:
        f = r["f"]
        last = r["evidence"][0]["decision"] if r["evidence"] else ""
        out.append([f["id"], f["institution_id"], f["inst_name"], f["fd_number"], f["bank_host"], float(f["principal"]),
                    f["issue_date"], f["maturity"], r["status"][1], r["status"][2] or "", last])
    return out


def to_csv(rows):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(HEAD)
    for row in register_rows(rows):
        w.writerow([safe_cell(c) if not isinstance(c, float) else f"{c:.2f}" for c in row])
    return buf.getvalue()


