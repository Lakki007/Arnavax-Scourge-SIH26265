def calendar(rows, months=72, today=None):
    today = today or date.today()
    out = {}
    for r in rows:
        if r["status"][0] in ("released", "renewed"):
            continue
        m = date.fromisoformat(r["f"]["maturity"])
        delta = (m.year - today.year) * 12 + m.month - today.month
        if delta < 0:
            key = "Overdue"
        elif delta >= months:
            continue
        else:
            key = m.strftime("%Y-%m")
        out.setdefault(key, []).append(r)
    keys = sorted(k for k in out if k != "Overdue")
    res = ([("Overdue", out["Overdue"])] if "Overdue" in out else []) + [(k, sorted(out[k], key=lambda r: r["f"]["maturity"])) for k in keys]
    return res


